void solve(){
    int n; cin >> n;

    const int LOG = 31;
    vector<int> basis(LOG, 0);

    for(int i = 0; i < n; i++){
        int x; cin >> x;

        for(int j = LOG-1; j >= 0; j--){
            if(!(x & (1 << j))) continue;

            if(!basis[j]){
                basis[j] = x;

                // normalizar base
                for(int k = 0; k < LOG; k++){
                    if(k != j && (basis[k] & (1 << j))){
                        basis[k] ^= basis[j];
                    }
                }
                break;
            }

            x ^= basis[j];
        }
    }

    int res = 0;
    for(int j = LOG-1; j >= 0; j--){
        res = max(res, res ^ basis[j]);
    }

    cout << res << '\n';
}

